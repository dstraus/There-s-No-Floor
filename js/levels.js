// There's No Floor - level data
// Coordinates: forward is -Z. For blocks, `y` is the TOP surface; objects placed at y sit on top.
// Player jumps ~2 blocks high and ~4 blocks far, so gaps are kept at 3 or less.
const B = (x, y, z, w = 3, d = 3, c) => ({ t: 'block', x, y, z, w, d, c });
const M = (x, y, z, w, d, to, period = 4, phase = 0) => ({ t: 'move', x, y, z, w, d, to, period, phase });
const S = (x, y, z) => ({ t: 'spike', x, y, z });
const C = (x, y, z) => ({ t: 'coin', x, y, z });
const K = (x, y, z) => ({ t: 'check', x, y, z });
const P = (x, y, z, kind) => ({ t: 'power', x, y, z, kind });
const SAW = (a, b, period = 3, phase = 0, axis) => ({ t: 'saw', a, b, period, phase, axis });
const BOMB = (x, y, z) => ({ t: 'bomb', x, y, z });
// Bouncing bomb: bounces h high every `period` seconds; optional `b` end point to also slide horizontally.
const BB = (x, y, z, h = 2.5, period = 1, b = null, mp = 4) => ({ t: 'bbomb', x, y, z, h, period, b, mp });
const F = (x, y, z) => ({ t: 'finish', x, y, z });

